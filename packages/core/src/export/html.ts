function page(title: string, body: string, style = ''): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<style>${STYLE}${style}</style>
</head>
<body>
${BRAND}
${body}
<footer>Generated by Ariadne on ${escapeHtml(new Date().toISOString().slice(0, 16).replace('T', ' '))} UTC.</footer>
</body>
</html>
`;
}

function img(src: string | undefined, alt: string): string {
  return src ? `<img class="shot" src="${escapeHtml(src)}" alt="${escapeHtml(alt)}">` : '';
}

function caseSection(doc: CaseDocument, image: ImageSource): string {
  const pre = doc.preconditions.map((line) => `<li>${escapeHtml(line)}</li>`).join('');
  const steps = doc.steps
    .map(
      (step) =>
        `<tr><td class="num">${step.number}</td><td>${escapeHtml(step.action)}</td><td>${escapeHtml(step.expected)}</td>` +
        `<td>${img(step.screenshot ? image(step.screenshot) : undefined, `Screen after step ${step.number}`)}</td></tr>`,
    )
    .join('');
  const checks = doc.endChecks.map((check) => `<li>${escapeHtml(check)}</li>`).join('');
  const status = doc.lastRun ? (doc.lastRun.passed ? 'passed' : 'failed') : 'not-run';
  return `<section class="case">
<h1>${escapeHtml(doc.name)}</h1>
<div class="meta">Case <code>${escapeHtml(doc.id)}</code>${doc.reference ? ` / reference ${escapeHtml(doc.reference)}` : ''} / app <code>${escapeHtml(doc.appId)}</code> / recorded ${escapeHtml(doc.createdAt.slice(0, 10))}${doc.editedAt ? ` / edited ${escapeHtml(doc.editedAt.slice(0, 10))}` : ''}${doc.muted ? ' / <span class="muted">muted</span>' : ''}</div>
<div>Last run: <span class="${status}">${escapeHtml(lastRunText(doc))}</span></div>
<h2>Preconditions</h2>
<ol>${pre}</ol>
<h2>Steps</h2>
${doc.steps.length === 0 ? '<p>No recorded steps.</p>' : `<table><thead><tr><th>#</th><th>Action</th><th>Expected result</th><th>Screen after</th></tr></thead><tbody>${steps}</tbody></table>`}
<h2>Expected at the end</h2>
${checks ? `<ul>${checks}</ul>` : '<p>No end checks.</p>'}
</section>`;
}

/** One printable page holding one or more test case documents. */
export function casesHtml(docs: readonly CaseDocument[], image: ImageSource, title: string): string {
  return page(title, docs.map((doc) => caseSection(doc, image)).join('\n'));
}

export type RunReportInput = {
  caseName: string;
  caseId: string;
  appId: string;
  run: RunSummary;
  rows: readonly ReportRow[];
  image: ImageSource;
  /** True when the case was edited after this run started. */
  stale?: boolean;
};

/** A replay, step by step, with the recorded and replayed screens side by side. */
export function runReportHtml(input: RunReportInput): string {
  const { run, rows, image } = input;
  const body = rows
    .map((row) => {
      const status = row.status ?? 'not-run';
      const similarity =
        row.similarity === undefined
          ? ''
          : `<div class="${row.looksDifferent ? 'warn' : ''}">${row.similarity}% alike${row.looksDifferent ? ', looks different' : ''}</div>`;
      const duration = row.durationMs === undefined ? '' : `<div class="meta">${formatDuration(row.durationMs)}</div>`;
      const recorded = row.recorded ? image(row.recorded) : undefined;
      const replayed = row.replayed ? image(row.replayed) : undefined;
      const shots =
        recorded || replayed
          ? `<div class="pair">${recorded ? `<figure>${img(recorded, `Recorded screen, step ${row.number}`)}<figcaption>recorded</figcaption></figure>` : ''}${replayed ? `<figure>${img(replayed, `Replayed screen, step ${row.number}`)}<figcaption>replayed</figcaption></figure>` : ''}</div>`
          : '';
      return (
        `<tr><td class="num">${row.number}</td><td>${escapeHtml(row.label)}${row.error ? `<div class="error">${escapeHtml(row.error)}</div>` : ''}</td>` +
        `<td class="${status}">${escapeHtml(status)}${duration}${similarity}</td><td>${shots}</td></tr>`
      );
    })
    .join('');
  const failure = run.failureScreenshot ? image(run.failureScreenshot) : undefined;
  const result = run.passed ? '<span class="passed">passed</span>' : '<span class="failed">failed</span>';
  return page(
    `${input.caseName}: run ${run.passed ? 'passed' : 'failed'}`,
    `<h1>${escapeHtml(input.caseName)}</h1>
<div class="meta">Case <code>${escapeHtml(input.caseId)}</code> / app <code>${escapeHtml(input.appId)}</code> / run <code>${escapeHtml(run.runId)}</code></div>
<p>Run ${result} on ${escapeHtml(run.startedAt.slice(0, 19).replace('T', ' '))} UTC with Maestro (exit code ${run.exitCode}).${input.stale ? ' <span class="warn">The case was edited after this run.</span>' : ''}${run.video ? ' <a href="video.mp4">Video</a>' : ''}</p>
${run.error ? `<p class="error">${escapeHtml(run.error)}</p>` : ''}
${failure ? `<h3>Screen when it failed</h3>${img(failure, 'Screen when the replay failed')}` : ''}
<h2>Steps</h2>
<table><thead><tr><th>#</th><th>Step</th><th>Result</th><th>Screens</th></tr></thead><tbody>${body}</tbody></table>`,
  );
}

export type SuiteReportCase = {
  name: string;
  caseId: string;
  outcome: SuiteCaseOutcome;
  attempts: number;
  failedStep?: string;
  error?: string;
  /** Why the case was retried when the device, not the app, failed. */
  note?: string;
  failureScreenshot?: string;
};

/** Run all, one row per case, with the failure screenshot of each failed case. */
export function suiteReportHtml(suite: SuiteRun, cases: readonly SuiteReportCase[], image: ImageSource): string {
  const rows = cases
    .map((item) => {
      const shot = item.failureScreenshot ? image(item.failureScreenshot) : undefined;
      const detail = [item.failedStep ? `Failed at: ${item.failedStep}` : '', item.error ?? '', item.note ?? ''].filter(Boolean).join('\n');
      return (
        `<tr><td>${escapeHtml(item.name)}<div class="meta">${escapeHtml(item.caseId)}</div></td>` +
        `<td class="${item.outcome}">${escapeHtml(item.outcome)}${item.attempts > 1 ? ` (${item.attempts} attempts)` : ''}</td>` +
        `<td>${detail ? `<div class="error">${escapeHtml(detail)}</div>` : ''}</td><td>${img(shot, `Failure screen of ${item.name}`)}</td></tr>`
      );
    })
    .join('');
  const counts = new Map<string, number>();
  for (const item of cases) counts.set(item.outcome, (counts.get(item.outcome) ?? 0) + 1);
  const summary = [...counts].map(([outcome, count]) => `${count} ${outcome}`).join(', ');
  return page(
    `Run all ${suite.suiteId}`,
    `<h1>Run all</h1>
<div class="meta">${escapeHtml(suite.suiteId)} / device ${escapeHtml(suite.deviceId)} / started ${escapeHtml(suite.startedAt.slice(0, 19).replace('T', ' '))} UTC${suite.retryFailed ? ' / failures retried once' : ''}</div>
<p>${escapeHtml(summary || 'No cases.')}${suite.status === 'running' ? ' (still running)' : ''}${suite.status === 'stopped' ? ' (stopped before the end)' : ''}</p>
<table><thead><tr><th>Case</th><th>Result</th><th>Details</th><th>Screen</th></tr></thead><tbody>${rows}</tbody></table>`,
  );
}

export type EvidenceInput = {
  suite: SuiteRun;
  /** One per case of the suite, in its order. */
  cases: readonly EvidenceCase[];
  /** What the release is called, as the person making the pack wrote it. */
  release?: string;
  testedBy?: string;
  /** The second signature's role; "Accepted by" unless the person making the pack wrote another, such as "Reviewed by". */
  signoffRole?: string;
  /** What the tester knows is wrong, in their words. */
  knownIssues?: string;
  /** The tester's verdict on the release, in their words. */
  conclusion?: string;
  /** Every step's screen, or only checks and the failed step. */
  screens?: ScreensMode;
  /** The Run all file the pack summarises. */
  record?: RecordFile;
  image: ImageSource;
  /** Formats a timestamp: local time with its offset unless a test sets it. */
  time?: (iso: string) => string;
};

